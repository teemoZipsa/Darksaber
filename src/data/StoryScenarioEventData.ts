function lateScenarioCacheEvent(
    dungeonId: string,
    episode: number,
    eventNumber: number,
    tile: TilePoint,
    originalItemId: number,
    itemId: string
): StoryScenarioFieldEvent {
    return {
        id: `${dungeonId}_cache_${eventNumber}`,
        originalSource: `MAP/${String(episode).padStart(2, '0')}set.arc:${String(episode).padStart(2, '0')}.evt`,
        originalEventId: `EVENT ${eventNumber}`,
        trigger: `COMMANDER original CHARPOS ${tile.x} ${tile.y} GETITEM ${originalItemId}`,
        triggerTiles: [{ ...tile }],
        runtimeFlag: `${dungeonId}_cache_${eventNumber}`,
        markerLabelKey: `story.event.ep${String(episode).padStart(2, '0')}.cache.marker`,
        markerKind: 'chest',
        rewards: [{ type: 'item', itemId, originalItemId }],
        steps: [{ kind: 'objective', labelKey: `story.event.ep${String(episode).padStart(2, '0')}.cache.recovered`, focus: { ...tile }, durationMs: LATE_STORY_STEP_DURATION_MS.cache }],
    };
}

function lateScenarioSequence(input: {
    dungeonId: string;
    episode: number;
    bossTile: TilePoint;
    globalScript: string;
    mapFiles: string[];
    dialogues?: Array<{ speakerId: string; speakerNameKey: string; textKey: string; focus?: TilePoint }>;
    bossDefeatDialogues?: Array<{ speakerId: string; speakerNameKey: string; textKey: string; focus?: TilePoint }>;
    caches: Array<{ eventNumber: number; tile: TilePoint; originalItemId: number; itemId: string }>;
}): StoryScenarioEventSequence {
    const ep = String(input.episode).padStart(2, '0');
    const originalFact = getOriginalLateStoryFact(input.episode);
    const objectiveRuntimeFlag = `${input.dungeonId}_objective_complete`;
    const layout = getStoryInteriorLayout(input.dungeonId);
    const entryAdvanceTile = layout ? { x: layout.playerStart.x, y: layout.playerStart.y - 1 } : null;
    const dialogueSteps = input.dialogues?.map((dialogue) => ({
        kind: 'dialogue' as const,
        speakerId: dialogue.speakerId,
        speakerNameKey: dialogue.speakerNameKey,
        textKey: dialogue.textKey,
        focus: dialogue.focus ?? input.bossTile,
        durationMs: LATE_STORY_STEP_DURATION_MS.dialogue,
    })) ?? [];
    const entry: StoryScenarioEventStep[] = [
        { kind: 'focus', target: input.bossTile, labelKey: `story.event.ep${ep}.focus.boss`, durationMs: LATE_STORY_STEP_DURATION_MS.focus },
        ...(entryAdvanceTile ? [{
            kind: 'moveActor' as const,
            actorId: 'hero',
            target: entryAdvanceTile,
            focus: entryAdvanceTile,
            durationMs: LATE_STORY_STEP_DURATION_MS.moveActor,
        }] : []),
        ...dialogueSteps,
        { kind: 'combatStart', labelKey: `story.event.ep${ep}.combatStart`, focus: input.bossTile, durationMs: LATE_STORY_STEP_DURATION_MS.combatStart },
    ];
    const bossClearItems = getOriginalLateStoryItemsForSourceEvent(input.episode, 99);
    const bossClearTriggerParts = [
        'ALL CHARDEAD 700',
        ...bossClearItems.map((item) => `GETITEM ${item.originalItemId}`),
        'SCENECLEAR',
    ];
    const bossDefeatEvent: StoryScenarioBossDefeatEvent = {
        id: `${input.dungeonId}_boss_clear_99`,
        originalSource: `MAP/${ep}set.arc:${ep}.evt`,
        originalEventId: 'EVENT 99',
        trigger: bossClearTriggerParts.join(' '),
        runtimeFlag: objectiveRuntimeFlag,
        ...(bossClearItems.length > 0
            ? { rewards: bossClearItems.map((item) => ({ type: 'item' as const, itemId: item.currentItemId, originalItemId: item.originalItemId })) }
            : {}),
    };

    return {
        dungeonId: input.dungeonId,
        originalSources: {
            sceneScript: `Wlib/scene${input.episode}.lsc`,
            globalScript: input.globalScript,
            mapFiles: input.mapFiles,
            setArcMembers: [
                originalFact.aiMember,
                originalFact.eventMember,
                ...(originalFact.deoMember ? [originalFact.deoMember] : []),
                ...(originalFact.deeMember ? [originalFact.deeMember] : []),
            ],
        },
        objectiveRuntimeFlag,
        entry,
        fieldEvents: input.caches.map((cache) => lateScenarioCacheEvent(
            input.dungeonId,
            input.episode,
            cache.eventNumber,
            cache.tile,
            cache.originalItemId,
            cache.itemId
        )),
        bossDefeatEvent,
        bossDefeat: [
            ...(input.bossDefeatDialogues?.map((dialogue) => ({
                kind: 'dialogue' as const,
                speakerId: dialogue.speakerId,
                speakerNameKey: dialogue.speakerNameKey,
                textKey: dialogue.textKey,
                focus: dialogue.focus ?? input.bossTile,
                durationMs: LATE_STORY_STEP_DURATION_MS.dialogue,
            })) ?? []),
            { kind: 'objective', labelKey: `story.event.ep${ep}.objective`, focus: input.bossTile, durationMs: LATE_STORY_STEP_DURATION_MS.objective },
        ],
    };
}

